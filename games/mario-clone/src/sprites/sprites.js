// Get sprite data for Mario based on power state
export function getMarioSprites(powerState) {
    switch (powerState) {
        case 'small':
            return SPRITES_SMALL_MARIO;
        case 'super':
        case 'fire':
        case 'star':
            return SPRITES_BIG_MARIO;
        default:
            return SPRITES_SMALL_MARIO;
    }
}

// Get object sprite
export function getObjectSprite(type, frame) {
    switch (type) {
        case 'question':
            return SPRITES_OBJECTS.questionIdle;
        case 'questionBumped':
            return SPRITES_OBJECTS.questionBumped;
        case 'questionUsed':
            return SPRITES_OBJECTS.questionUsed;
        case 'brick':
            return SPRITES_OBJECTS.brick;
        case 'coin':
            // Coin has 4-frame animation
            const coinFrames = ['coin1', 'coin2', 'coin3', 'coin4'];
            return SPRITES_OBJECTS[coinFrames[frame % 4]];
        case 'mushroom':
            return SPRITES_OBJECTS.mushroom;
        case 'fireFlower':
            return SPRITES_OBJECTS.fireFlower;
        case 'star':
            return SPRITES_OBJECTS.star;
        default:
            return null;
    }
}
